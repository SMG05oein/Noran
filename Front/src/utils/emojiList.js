/**
 * emojiIdx로 이모지 문자열을 반환하는 헬퍼 함수
 * @param {number|string} idx - 이모지 인덱스
 * @param {string} fallback - 기본 이모지 (기본값: '🐷')
 * @returns {string} 이모지 문자
 */
export const getEmojiByIdx = (idx, fallback = '🐷') => {
  const num = Number(idx);
  if (isNaN(num) || num < 0 || num >= EMOJI_LIST.length) {
    return fallback;
  }
  return EMOJI_LIST[num];
};
